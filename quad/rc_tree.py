"""SPEF RC transfer resistance: exact Elmore sensitivity to each sink cap.

For a tree, d tau_sink / d C_pin is shared root-path resistance. For a
resistive mesh it is the corresponding grounded conductance inverse entry.
SPEF is generated by the same OpenROAD global-route estimator as reference STA.
"""
from collections import defaultdict
import re
import numpy as np
from scipy.sparse import coo_matrix,csc_matrix
from scipy.sparse.linalg import splu

def spef_networks(path):
    section=None;net=None;res=[];conn={};wire={};cap_ff=None;res_kohm=None
    with open(path) as f:
        for line in f:
            v=line.split()
            if not v:continue
            if v[0]=='*R_UNIT':
                units={'OHM':1e-3,'KOHM':1.,'MOHM':1e3}
                if v[2] not in units:raise ValueError('Unsupported SPEF resistance unit')
                res_kohm=float(v[1])*units[v[2]]
            if v[0]=='*C_UNIT':
                units={'FF':1.,'PF':1e3,'NF':1e6}
                if v[2] not in units:raise ValueError('Unsupported SPEF capacitance unit')
                cap_ff=float(v[1])*units[v[2]]
            if v[0]=='*NAME_MAP':raise ValueError('Named OpenROAD SPEF required')
            if v[0]=='*D_NET':
                if cap_ff is None or res_kohm is None:raise ValueError('Missing SPEF units')
                net=re.sub(r'\\(.)',r'\1',v[1]);res=[];conn={};wire={};section=None
            elif v[0] in ('*CONN','*CAP','*RES'):section=v[0]
            elif v[0]=='*END':yield net,conn,res,wire;net=None;section=None
            elif net is not None:
                if section=='*CONN' and v[0] in ('*I','*P'):
                    name=v[1].rsplit(':',1)[0]+'/'+v[1].rsplit(':',1)[1] if v[0]=='*I' else v[1]
                    # Decode logical identifiers only. RC-node keys keep their
                    # original SPEF spelling for matching CAP/RES sections.
                    conn[v[1]]=re.sub(r'\\(.)',r'\1',name)
                elif section=='*RES':res.append((v[1],v[2],float(v[3])*res_kohm))
                elif section=='*CAP':
                    if len(v)!=3:raise ValueError('Unexpected coupling cap in route estimate')
                    wire[v[1]]=float(v[2])*cap_ff

def transfer_resistance(root,loads,resistors):
    # Estimator SPEF legitimately contains zero-ohm pin/segment connections.
    # Contract them exactly instead of introducing a numerical resistance.
    leaders={}
    def find(x):
        leaders.setdefault(x,x)
        if leaders[x]!=x:leaders[x]=find(leaders[x])
        return leaders[x]
    for a,b,r in resistors:
        if r<0:raise ValueError('Negative SPEF resistance')
        if r==0:leaders[find(a)]=find(b)
    root=find(root);loads=[find(x) for x in loads]
    resistors=[(find(a),find(b),r) for a,b,r in resistors if r>0 and find(a)!=find(b)]
    adj=defaultdict(list)
    for a,b,r in resistors:
        if a==b:continue
        adj[a].append((b,r));adj[b].append((a,r))
    parent={root:None};distance={root:0.};queue=[root]
    for p in queue:
        for q,r in adj[p]:
            if q not in parent:parent[q]=p;distance[q]=distance[p]+r;queue.append(q)
    if any(x not in parent for x in loads):raise ValueError('Disconnected sink RC network')
    if len(resistors)==len(parent)-1:
        result=np.zeros((len(loads),len(loads)))
        for i,x in enumerate(loads):
            ancestors=set();p=x
            while p is not None:ancestors.add(p);p=parent[p]
            for j in range(i,len(loads)):
                p=loads[j]
                while p not in ancestors:p=parent[p]
                result[i,j]=result[j,i]=distance[p]
        return result,'tree'
    nodes=[p for p in queue if p!=root];idx={p:i for i,p in enumerate(nodes)};rr=[];cc=[];vv=[]
    for a,b,r in resistors:
        if a not in parent or b not in parent:continue
        g=1/r
        for p in (a,b):
            if p!=root:rr.append(idx[p]);cc.append(idx[p]);vv.append(g)
        if a!=root and b!=root:rr.extend([idx[a],idx[b]]);cc.extend([idx[b],idx[a]]);vv.extend([-g,-g])
    mat=coo_matrix((vv,(rr,cc)),shape=(len(nodes),len(nodes))).tocsc();rhs=np.zeros((len(nodes),len(loads)))
    for j,p in enumerate(loads):
        if p!=root:rhs[idx[p],j]=1.
    sol=splu(mat).solve(rhs);result=np.zeros((len(loads),len(loads)))
    for i,p in enumerate(loads):
        if p!=root:result[i]=sol[idx[p]]
    return result,'mesh'

def build_sensitivity(model,path):
    m=model;by_net=defaultdict(list)
    for k,a in enumerate(m.arcs):
        a['arc_index']=k
        if a['role']=='wire':by_net[m.pins[a['s']]['net']].append(k)
    rr=[];cc=[];vv=[];covered=set();counts=defaultdict(int)
    for net,conn,res,wire in spef_networks(path):
        arcids=by_net.get(net,[])
        if not arcids:continue
        drivers={m.pins[m.arcs[k]['s']]['name'] for k in arcids}
        if len(drivers)!=1:raise ValueError('Multiple RC drivers unsupported')
        inverse={pin:node for node,pin in conn.items()};root=inverse[next(iter(drivers))]
        pins=[(node,m.index[pin]) for node,pin in conn.items() if pin in m.index and node!=root]
        loads=[node for node,pin in pins];matrix,kind=transfer_resistance(root,loads,res);counts[kind]+=1;where={pin:i for i,(_,pin) in enumerate(pins)}
        for k in arcids:
            dest=m.arcs[k]['t']
            if dest not in where:raise ValueError(f'Wire sink missing from SPEF: net={net!r} sink={m.pins[dest]["name"]!r} connections={conn!r}')
            row=matrix[where[dest]]
            for j,value in enumerate(row):
                if value>0:rr.append(k);cc.append(pins[j][1]*2+m.arcs[k]['fr']);vv.append(value)
            covered.add(k)
    missing=[k for ids in by_net.values() for k in ids if k not in covered and abs(m.arcs[k]['elmore'])>1e-8]
    if missing:raise ValueError(f'{len(missing)} nonzero Elmore arcs absent from SPEF')
    result=coo_matrix((vv,(rr,cc)),shape=(len(m.arcs),m.n*2)).tocsr()
    return result,dict(counts,nonzeros=result.nnz,covered_wire_arcs=len(covered),zero_or_ideal_uncovered=sum(len(x) for x in by_net.values())-len(covered))
